-- Migration: 023_free_tracker_growth
--
-- Everything the "free tracker + growth" release needs, in one migration so dev
-- and production cannot end up half-applied:
--
--   1. feature_limits: a cap on saved jobs, and daily caps for the two new AI
--      features (LinkedIn optimiser, mock interview).
--   2. tracked_jobs.follow_up_at: follow-up reminders in the tracker.
--   3. funnel_events: first-party product analytics (signup -> scan -> save -> pay).
--   4. ai_generations: one row per LinkedIn / interview AI call, counted by the caps.
--   5. email_prefs + email_log: lifecycle emails with one-click unsubscribe, and
--      a log so the same email is never sent twice.
--
-- Safe to run more than once.

-- -----------------------------------------------------------------------------
-- 1. Caps
-- -----------------------------------------------------------------------------
-- NULL MEANS UNLIMITED (see migration 011). Every new column is therefore given
-- an explicit value for `free` below; forgetting that would make the capped
-- features unlimited for free users.

alter table public.feature_limits
  add column if not exists max_tracked_jobs int,
  add column if not exists max_linkedin_per_day int,
  add column if not exists max_interview_per_day int;

alter table public.feature_limits drop constraint if exists feature_limits_tj_range;
alter table public.feature_limits
  add constraint feature_limits_tj_range check (max_tracked_jobs is null or max_tracked_jobs >= 0);
alter table public.feature_limits drop constraint if exists feature_limits_li_range;
alter table public.feature_limits
  add constraint feature_limits_li_range check (max_linkedin_per_day is null or max_linkedin_per_day >= 0);
alter table public.feature_limits drop constraint if exists feature_limits_iv_range;
alter table public.feature_limits
  add constraint feature_limits_iv_range check (max_interview_per_day is null or max_interview_per_day >= 0);

-- Free: the tracker is free up to 50 saved jobs; one LinkedIn rewrite and one
-- interview practice session a day as a taster.
update public.feature_limits
   set max_tracked_jobs = 50,
       max_linkedin_per_day = 1,
       max_interview_per_day = 1
 where plan = 'free';

-- Full access: unlimited tracking; AI features capped per day because every
-- call is paid for by us (same reasoning as the 20/40 resume caps in 011).
update public.feature_limits
   set max_tracked_jobs = null,
       max_linkedin_per_day = 10,
       max_interview_per_day = 10
 where plan = 'student_pro';

-- -----------------------------------------------------------------------------
-- 2. Follow-up reminders
-- -----------------------------------------------------------------------------

alter table public.tracked_jobs
  add column if not exists follow_up_at date;

create index if not exists tracked_jobs_follow_up_idx
  on public.tracked_jobs (follow_up_at)
  where follow_up_at is not null;

-- -----------------------------------------------------------------------------
-- 3. Funnel analytics
-- -----------------------------------------------------------------------------
-- First-party and minimal: an event name, the user (when known) and a few
-- non-personal properties. No page content, resume text or job text is ever
-- stored here. Written by the service role only; nobody can read it from the
-- browser.

create table if not exists public.funnel_events (
  id         bigint generated by default as identity primary key,
  user_id    uuid,
  event      text not null,
  props      jsonb not null default '{}',
  created_at timestamptz not null default now(),
  constraint funnel_events_event_shape check (event ~ '^[a-z][a-z0-9_]{1,48}$')
);

create index if not exists funnel_events_event_created_idx
  on public.funnel_events (event, created_at desc);

alter table public.funnel_events enable row level security;
-- No policies: service role only.

-- -----------------------------------------------------------------------------
-- 4. AI generations (LinkedIn optimiser, mock interview)
-- -----------------------------------------------------------------------------
-- One row per AI call. The daily caps count rows created in the current UTC day,
-- the same way resume scans are counted. Output is kept for 30 days so the
-- pages can show the last result; nothing here is needed after that.

create table if not exists public.ai_generations (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references auth.users(id) on delete cascade,
  kind       text not null,
  output     jsonb not null default '{}',
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  constraint ai_generations_kind_check
    check (kind in ('linkedin', 'interview_questions', 'interview_feedback'))
);

create index if not exists ai_generations_user_kind_created_idx
  on public.ai_generations (user_id, kind, created_at desc);

alter table public.ai_generations enable row level security;
drop policy if exists ai_generations_select_own on public.ai_generations;
create policy ai_generations_select_own on public.ai_generations
  for select using (user_id = auth.uid());

-- -----------------------------------------------------------------------------
-- 5. Email preferences and log
-- -----------------------------------------------------------------------------
-- A missing prefs row means "all emails on". Unsubscribing writes a row.

create table if not exists public.email_prefs (
  user_id         uuid primary key references auth.users(id) on delete cascade,
  reminders       boolean not null default true,
  digest          boolean not null default true,
  unsubscribed_at timestamptz,
  updated_at      timestamptz not null default now()
);

alter table public.email_prefs enable row level security;
drop policy if exists email_prefs_select_own on public.email_prefs;
create policy email_prefs_select_own on public.email_prefs
  for select using (user_id = auth.uid());

-- `dedupe_key` makes every send idempotent: a cron that runs twice, or a retry
-- after a timeout, cannot email the same person the same thing again.
create table if not exists public.email_log (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  kind       text not null,
  dedupe_key text not null,
  sent_at    timestamptz not null default now(),
  constraint email_log_kind_check check (kind in ('welcome', 'reminder', 'digest'))
);

create unique index if not exists email_log_dedupe_uidx on public.email_log (dedupe_key);

alter table public.email_log enable row level security;
-- No policies: service role only.

